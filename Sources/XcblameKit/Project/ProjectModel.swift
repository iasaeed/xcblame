import Foundation

/// Read-only understanding of an Xcode project, workspace or Swift package (DESIGN §4.1 `ProjectModel`, §7.4): what
/// the project file, its xcconfigs, schemes and dependency manifests say, before `xcodebuild` resolves anything.
/// Effective values come from `SettingsOracle`; this model is the provenance side. Contract: docs/SCHEMA-v0.3.md.
/// Lane A fills `load`; nothing here ever writes to the project.
public struct ProjectModel: Codable, Sendable, Equatable {
    public enum Container: Codable, Sendable, Equatable {
        case xcodeproj(URL)
        case xcworkspace(URL)
        /// The `Package.swift` file of a package opened without a project.
        case package(URL)

        public var url: URL {
            switch self {
            case let .xcodeproj(url), let .xcworkspace(url), let .package(url): return url
            }
        }
    }

    public enum Format: Codable, Sendable, Equatable {
        /// OpenStep `project.pbxproj`; for a workspace, the format of its first project.
        case pbxproj(objectVersion: Int)
        /// Xcode 27.2 JSON `project.xcproj` (read only after MV-4).
        case xcproj
        case package
    }

    public enum DependencyManager: Codable, Sendable, Equatable {
        case cocoapods(podfile: URL, lockfile: URL?, podCount: Int?)
        case carthage(cartfile: URL)
        /// Any Swift package reference (remote or local) or a `Package.swift` container.
        case spm

        /// `cocoapods` / `carthage` / `spm`.
        public var name: String {
            switch self {
            case .cocoapods: return "cocoapods"
            case .carthage: return "carthage"
            case .spm: return "spm"
            }
        }
    }

    public enum Generator: Codable, Sendable, Equatable {
        case xcodegen(spec: URL)
        case tuist(manifest: URL)
        case other(name: String)

        /// `xcodegen` / `tuist` / the other generator's name.
        public var name: String {
            switch self {
            case .xcodegen: return "xcodegen"
            case .tuist: return "tuist"
            case let .other(name): return name
            }
        }
    }

    /// The directory holding the container (the repository side of the project).
    public var root: URL
    public var container: Container
    public var format: Format
    /// One per `.xcodeproj` a workspace references (or the container itself). CocoaPods' `Pods/Pods.xcodeproj` is not
    /// read: its targets are regenerated by `pod install`; a note and the `cocoapods` manager stand for it.
    public var projects: [Project]
    /// Shared and user schemes of every project and the workspace.
    public var schemes: [Scheme]
    /// Remote and local Swift package references, deduplicated by URL or path across projects. For a `.package`
    /// container: the root package itself, as a local reference with its manifest.
    public var packages: [PackageReference]
    public var dependencyManagers: [DependencyManager]
    /// Nil when no generator source was found next to the container.
    public var generator: Generator?
    public var notes: [String]

    public init(root: URL, container: Container, format: Format, projects: [Project] = [], schemes: [Scheme] = [],
                packages: [PackageReference] = [], dependencyManagers: [DependencyManager] = [],
                generator: Generator? = nil, notes: [String] = []) {
        self.root = root
        self.container = container
        self.format = format
        self.projects = projects
        self.schemes = schemes
        self.packages = packages
        self.dependencyManagers = dependencyManagers
        self.generator = generator
        self.notes = notes
    }

    /// Every target of every project, in project order.
    /// Every project target in project order. A name used by targets of several projects is qualified as
    /// `<project name>/<target name>` on each of them, so effective settings, provenance and rule scopes are keyed per
    /// (project, target) (`EffectiveSettings.targets` uses the same keys).
    public var allTargets: [Target] {
        let counts = Dictionary(projects.flatMap { $0.targets.map { ($0.name, 1) } }, uniquingKeysWith: +)
        return projects.flatMap { project in
            project.targets.map { target in
                guard counts[target.name, default: 0] > 1 else { return target }
                var qualified = target
                qualified.name = project.name + "/" + target.name
                return qualified
            }
        }
    }

    /// Configuration names across projects, first-seen order.
    public var configurationNames: [String] {
        var seen: Set<String> = []
        return projects.flatMap(\.configurations).filter { seen.insert($0).inserted }
    }

    /// Reads the container (Lane A). `scheme` narrows nothing structural; it is recorded so readers can resolve
    /// scheme-only facts (e.g. which targets a scheme builds) when they need them.
    public static func load(container: URL, scheme: String?) throws -> ProjectModel {
        try ProjectModelLoader.load(container: container, scheme: scheme)
    }
}

/// One build setting as written at one level. Conditional assignments (`KEY[sdk=iphonesimulator*] = …`) are kept
/// under the base key.
public struct SettingValue: Codable, Sendable, Equatable {
    /// The unconditional value as written (`$(inherited)` and other references unexpanded). A pbxproj array value is
    /// joined with single spaces, elements containing whitespace double-quoted. Nil when the key is only set
    /// conditionally.
    public var raw: String?
    /// Condition text without brackets (`sdk=iphonesimulator*`, `arch=arm64`, `config=Debug`, several joined by `][`)
    /// to the value written for it. Nil when there are none.
    public var conditions: [String: String]?

    public init(raw: String?, conditions: [String: String]? = nil) {
        self.raw = raw
        self.conditions = conditions
    }
}

extension ProjectModel {
    public struct Project: Codable, Sendable, Equatable {
        /// The `.xcodeproj` bundle.
        public var path: URL
        public var name: String
        /// Nil for an `.xcproj` project.
        public var objectVersion: Int?
        /// Project-level `XCConfigurationList` order.
        public var configurations: [String]
        /// The configuration `analyze` evaluates when the log names none: the `LaunchAction` configuration of the
        /// requested scheme (else of the project's first shared, then user scheme), else `Debug` when present, else
        /// the project list's `defaultConfigurationName`, else the first configuration.
        public var defaultConfiguration: String?
        /// Configuration name to the project-level `buildSettings` written in the project file.
        public var projectSettings: [String: [String: SettingValue]]
        /// Configuration name to its project-level `baseConfigurationReference` xcconfig, resolved to a file URL.
        /// A configuration without one has no key.
        public var projectXCConfig: [String: URL]
        public var targets: [Target]

        public init(path: URL, name: String, objectVersion: Int?, configurations: [String],
                    defaultConfiguration: String? = nil, projectSettings: [String: [String: SettingValue]] = [:],
                    projectXCConfig: [String: URL] = [:], targets: [Target] = []) {
            self.path = path
            self.name = name
            self.objectVersion = objectVersion
            self.configurations = configurations
            self.defaultConfiguration = defaultConfiguration
            self.projectSettings = projectSettings
            self.projectXCConfig = projectXCConfig
            self.targets = targets
        }
    }

    public struct Target: Codable, Sendable, Equatable {
        public enum FrameworkKind: String, Codable, Sendable, Equatable {
            case `static`, dynamic
        }

        /// The 24-hex object id in the pbxproj (the id in `.xcproj`).
        public var id: String
        public var name: String
        /// Raw `productType`, e.g. `com.apple.product-type.application`, `com.apple.product-type.framework`,
        /// `com.apple.product-type.library.static`, `com.apple.product-type.bundle.unit-test`; empty for an aggregate.
        public var productType: String
        public var hasSwiftSources: Bool
        /// C, ObjC or C++ sources (`.c`, `.m`, `.mm`, `.cpp`, `.cc`).
        public var hasCSources: Bool
        /// `SWIFT_OBJC_BRIDGING_HEADER` set in any configuration at the target or project level, or in an xcconfig.
        public var hasBridgingHeader: Bool
        /// Configuration name to the target-level `buildSettings` written in the project file.
        public var settings: [String: [String: SettingValue]]
        /// Configuration name to the target-level `baseConfigurationReference` xcconfig; no key when none.
        public var xcconfig: [String: URL]
        /// In build order.
        public var phases: [BuildPhase]
        /// Names of targets this target depends on (`PBXTargetDependency`), same or other project.
        public var dependencies: [String]
        /// Swift package product names linked (`XCSwiftPackageProductDependency.productName`).
        public var packageProducts: [String]
        /// `static` / `dynamic` for frameworks and libraries (`MACH_O_TYPE` or the product type); nil otherwise.
        public var frameworkKind: FrameworkKind?
        /// Unit or UI test bundle.
        public var isTest: Bool

        public init(id: String, name: String, productType: String, hasSwiftSources: Bool = false,
                    hasCSources: Bool = false, hasBridgingHeader: Bool = false,
                    settings: [String: [String: SettingValue]] = [:], xcconfig: [String: URL] = [:],
                    phases: [BuildPhase] = [], dependencies: [String] = [], packageProducts: [String] = [],
                    frameworkKind: FrameworkKind? = nil, isTest: Bool = false) {
            self.id = id
            self.name = name
            self.productType = productType
            self.hasSwiftSources = hasSwiftSources
            self.hasCSources = hasCSources
            self.hasBridgingHeader = hasBridgingHeader
            self.settings = settings
            self.xcconfig = xcconfig
            self.phases = phases
            self.dependencies = dependencies
            self.packageProducts = packageProducts
            self.frameworkKind = frameworkKind
            self.isTest = isTest
        }
    }

    public enum BuildPhase: Codable, Sendable, Equatable {
        case shellScript(ShellScriptPhase)
        /// Files in the Sources phase (synchronized root groups count their member files).
        case sources(count: Int)
        /// Files in Copy Bundle Resources; `largeFileBytes` sums files over 10 MB, nil when not measured.
        case resources(count: Int, largeFileBytes: Int64?)
        /// Frameworks, headers, copy-files and other phases, by name (`PBXFrameworksBuildPhase`, ...).
        case other(name: String)
    }

    public struct ShellScriptPhase: Codable, Sendable, Equatable {
        public var id: String
        /// `name`, or `Run Script` when unnamed.
        public var name: String
        /// Script text, unescaped (`\n` as newlines; objectVersion 90 arrays joined with newlines).
        public var shellScript: String
        public var inputPaths: [String]
        public var outputPaths: [String]
        public var inputFileListPaths: [String]
        public var outputFileListPaths: [String]
        /// `alwaysOutOfDate = 1` ("Based on dependency analysis" unchecked).
        public var alwaysOutOfDate: Bool
        /// "For install builds only".
        public var runOnlyForDeploymentPostprocessing: Bool

        public init(id: String, name: String, shellScript: String, inputPaths: [String] = [], outputPaths: [String] = [],
                    inputFileListPaths: [String] = [], outputFileListPaths: [String] = [], alwaysOutOfDate: Bool = false,
                    runOnlyForDeploymentPostprocessing: Bool = false) {
            self.id = id
            self.name = name
            self.shellScript = shellScript
            self.inputPaths = inputPaths
            self.outputPaths = outputPaths
            self.inputFileListPaths = inputFileListPaths
            self.outputFileListPaths = outputFileListPaths
            self.alwaysOutOfDate = alwaysOutOfDate
            self.runOnlyForDeploymentPostprocessing = runOnlyForDeploymentPostprocessing
        }
    }

    public struct PackageReference: Codable, Sendable, Equatable {
        public enum Requirement: Codable, Sendable, Equatable {
            case exact(String)
            case upToNextMajor(String)
            case upToNextMinor(String)
            case range(from: String, to: String)
            case branch(String)
            case revision(String)
            /// A local package (`XCLocalSwiftPackageReference` or `.package(path:)`).
            case local
        }

        /// Remote repository URL as written; nil for a local package.
        public var url: String?
        /// Local package directory (absolute); nil for a remote package.
        public var path: URL?
        public var requirement: Requirement
        /// Products of this package linked by project targets (or, inside a manifest, used by its targets).
        public var products: [String]
        /// Names of the targets that link one of `products`.
        public var consumers: [String]
        /// Parsed `Package.swift` of a local package (or of the `.package` container); nil for a remote package or when
        /// the manifest could not be read (with a note).
        public var manifest: PackageManifest?

        public init(url: String?, path: URL?, requirement: Requirement, products: [String] = [], consumers: [String] = [],
                    manifest: PackageManifest? = nil) {
            self.url = url
            self.path = path
            self.requirement = requirement
            self.products = products
            self.consumers = consumers
            self.manifest = manifest
        }
    }

    /// What the rules need from a `Package.swift`, read as text (never `swift package dump-package`, which may write
    /// `.build/`).
    public struct PackageManifest: Codable, Sendable, Equatable {
        public struct PackageTarget: Codable, Sendable, Equatable {
            public var name: String
            /// `regular` / `executable` / `test` / `macro` / `plugin` / `binary` / `system`.
            public var type: String
            /// Target and product names it depends on, as written (`.product(name: "SwiftSyntax", ...)` → `SwiftSyntax`).
            public var dependencies: [String]
            /// Build-tool plugins applied with `plugins: [...]`.
            public var plugins: [String]

            public init(name: String, type: String, dependencies: [String] = [], plugins: [String] = []) {
                self.name = name
                self.type = type
                self.dependencies = dependencies
                self.plugins = plugins
            }
        }

        public var name: String?
        /// The manifest's own `.package(...)` dependencies (`products`/`consumers` filled from `targets`).
        public var dependencies: [PackageReference]
        public var targets: [PackageTarget]

        public init(name: String?, dependencies: [PackageReference] = [], targets: [PackageTarget] = []) {
            self.name = name
            self.dependencies = dependencies
            self.targets = targets
        }
    }

    public struct Scheme: Codable, Sendable, Equatable {
        public var name: String
        /// The `.xcscheme` file.
        public var path: URL
        /// `BuildAction parallelizeBuildables`; nil when the attribute is absent.
        public var parallelizeBuildables: Bool?
        /// `BuildAction buildImplicitDependencies`; nil when absent.
        public var buildImplicitDependencies: Bool?
        /// Under `xcshareddata/xcschemes` (false: `xcuserdata`).
        public var isShared: Bool

        public init(name: String, path: URL, parallelizeBuildables: Bool?, buildImplicitDependencies: Bool?,
                    isShared: Bool) {
            self.name = name
            self.path = path
            self.parallelizeBuildables = parallelizeBuildables
            self.buildImplicitDependencies = buildImplicitDependencies
            self.isShared = isShared
        }
    }
}

/// One `.xcconfig` file with its own assignments; includes are listed, not merged (the resolver merges).
public struct XCConfigFile: Codable, Sendable, Equatable {
    public var url: URL
    /// Assignments in this file only, later lines winning, conditional keys under their base key.
    public var settings: [String: SettingValue]
    /// `#include "…"` targets that exist, resolved relative to this file, in file order.
    public var includes: [URL]
    /// `#include? "…"` targets that exist.
    public var optionalIncludes: [URL]
    /// Include targets (either form) that do not exist; a missing `#include` (not `?`) breaks the build.
    public var missingIncludes: [URL]

    public init(url: URL, settings: [String: SettingValue] = [:], includes: [URL] = [], optionalIncludes: [URL] = [],
                missingIncludes: [URL] = []) {
        self.url = url
        self.settings = settings
        self.includes = includes
        self.optionalIncludes = optionalIncludes
        self.missingIncludes = missingIncludes
    }

    /// Parses one xcconfig (Lane A).
    public static func load(url: URL) throws -> XCConfigFile {
        try XCConfigReader.parse(url: url).file
    }
}
