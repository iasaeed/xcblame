import Foundation

// v0.6 lane C (docs/SCHEMA-v0.6.md "Text"): the `fix` plan as text.
extension TextReporter {
    /// The steps in plan order (rule, title, band, confidence, fix kind, mechanism as a sentence, verify state, scope per
    /// mechanism, overlay and defaults lines), then the guards, the hook per configuration, the commands to run, the
    /// writes made with the plan, and "nothing in the project changed" unless `wrote` (a write flag ran).
    public static func renderFixPlan(_ plan: FixPlanDocument, colors: Bool = false, wrote: Bool = false) -> String {
        let text = TextReporter(colors: colors)
        var lines: [String] = []
        var head = "xcblame fix plan \(text.safe(plan.id)) · " + text.safe(URL(fileURLWithPath: plan.project.container).lastPathComponent)
        if let scheme = plan.project.scheme { head += " · scheme \(text.safe(scheme))" }
        if !plan.project.configurations.isEmpty { head += " · " + plan.project.configurations.map(text.safe).joined(separator: ", ") }
        lines.append(text.bold(head))
        lines.append("  " + FixPlanWords.source(plan.generatedFrom))
        lines.append("  " + FixPlanWords.summary(plan))
        if let generator = plan.project.generator {
            lines.append(text.warn("  generated by \(text.safe(generator)): the hook goes into the generator's source, not the project"))
        }

        lines += ["", text.bold("STEPS")]
        if plan.steps.isEmpty { lines.append("  no step: no finding has a fix xcblame can plan") }
        for step in plan.steps { lines += stepLines(step, text: text) }

        if !plan.guards.isEmpty {
            lines += ["", text.bold("GUARDS")]
            for item in plan.guards {
                let mark = item.satisfied.map { $0 ? "[x]" : "[ ]" } ?? "[?]"
                let rules = item.ruleIds.isEmpty ? "" : " (" + item.ruleIds.joined(separator: ", ") + ")"
                lines.append("  \(mark) " + text.safe(item.text) + rules)
            }
            if plan.guards.contains(where: { $0.satisfied == nil }) { lines.append(text.dim("  [?] not checked (offline or no git)")) }
        }
        if !plan.hook.isEmpty {
            lines += ["", text.bold("HOOK")]
            lines += plan.hook.map { "  " + text.safe(FixPlanWords.hookLine($0)) }
        }
        if !plan.commands.isEmpty {
            lines += ["", text.bold("RUN")]
            lines += plan.commands.enumerated().map { "  \($0.offset + 1). \(text.safe($0.element))" }
        }
        if !plan.events.isEmpty {
            lines += ["", text.bold("WRITES")]
            lines += plan.events.map { "  " + text.safe(FixPlanWords.eventLine($0)) }
        }
        if !plan.notes.isEmpty { lines += [""] + plan.notes.map { text.dim("note: " + text.safe($0)) } }
        lines.append("")
        lines.append(wrote ? "the project changed: see WRITES; xcblame fix --revert \(text.safe(plan.id)) undoes it"
            : "nothing in the project changed: the plan is stored in xcblame's state (plans/\(text.safe(plan.id)).json)")
        return lines.joined(separator: "\n") + "\n"
    }

    private static func stepLines(_ step: FixPlanDocument.Step, text: TextReporter) -> [String] {
        let pad = "     "
        var lines = ["  \(step.order). " + text.bold(text.safe(step.ruleId)) + "  " + text.safe(step.title)]
        lines.append(pad + [FixPlanWords.impact(step), "confidence \(text.safe(step.confidence))", "fix kind \(step.fixKind.rawValue)"]
            .joined(separator: " · "))
        lines.append(pad + "how: " + step.mechanism.rawValue + ", " + FixVerifyWords.mechanismSentence(step.mechanism))
        if let detail = step.mechanismDetail, detail != step.mechanism.rawValue { lines.append(pad + text.dim("detail: " + text.safe(detail))) }
        let verify = FixPlanWords.verifyLine(step)
        lines.append(pad + "verify: " + (step.verify.status == .kept ? verify : step.verify.status == .reverted ? text.fail(verify) : verify))
        if step.verifyOnly { lines.append(pad + "+V: written only after verify keeps it (--force-unverified does not override this)") }
        for mechanism in FixPlanDocument.Mechanism.allCases {
            let rows = step.scope.filter { $0.mechanism == mechanism }
            guard !rows.isEmpty else { continue }
            lines.append(pad + "scope \(mechanism.rawValue): " + text.safe(FixVerifyWords.scopeSummary(rows)))
        }
        if step.shadowing != .none {
            lines.append(pad + text.warn("shadowed (\(step.shadowing.rawValue)) for the hook by "
                + (step.shadowedBy.isEmpty ? "a higher level" : step.shadowedBy.map(text.safe).joined(separator: ", "))))
        }
        lines += step.overlay.map { pad + "overlay \(text.safe($0.configuration)): " + text.safe($0.line) }
        lines += step.defaults.map { pad + "defaults: " + text.safe(FixPlanWords.defaultsCommand($0)) }
        lines += step.inXcode.map { pad + "by hand: " + text.safe($0) }
        if let risk = step.risk, !risk.isEmpty { lines.append(pad + "risk: " + text.safe(risk)) }
        if step.state != .planned {
            lines.append(pad + "state: \(step.state.rawValue)" + (step.stateReason.map { ": " + text.safe($0) } ?? ""))
        }
        return lines
    }
}

/// The fix-plan sentences shared by text, markdown and agent.
enum FixPlanWords {
    static func source(_ source: FixPlanDocument.Source) -> String {
        let from: String
        if let id = source.analysisId {
            from = "from history entry \(id)" + (source.analysisKind.map { " (\($0) build)" } ?? "")
        } else if let path = source.analysisPath {
            from = "from the report \(URL(fileURLWithPath: path).lastPathComponent)" + (source.analysisKind.map { " (\($0) build)" } ?? "")
        } else {
            from = "from settings only (no recorded build: impact is the catalog estimate)"
        }
        var out = FormatText.oneLine(from) + " · settings from \(FormatText.oneLine(source.settingsSource))"
        if !source.rulesFilter.isEmpty { out += " · rules " + source.rulesFilter.joined(separator: ",") }
        return out
    }

    /// `3 steps: 2 overlay, 1 defaults · verify: 1 kept, 2 unverified`.
    static func summary(_ plan: FixPlanDocument) -> String {
        func grouped<T: Hashable>(_ values: [T], _ name: (T) -> String) -> String {
            var order: [T] = []
            var count: [T: Int] = [:]
            for value in values {
                if count[value] == nil { order.append(value) }
                count[value, default: 0] += 1
            }
            return order.map { "\(count[$0] ?? 0) \(name($0))" }.joined(separator: ", ")
        }
        guard !plan.steps.isEmpty else { return "0 steps" }
        return FormatText.count(plan.steps.count, "step") + ": " + grouped(plan.steps.map(\.fixKind)) { $0.rawValue }
            + " · verify: " + grouped(plan.steps.map { FixVerifyWords.stateLabel($0.verify) }) { $0 }
    }

    /// `measured S, about 2.50 s` / `estimated M (catalog)` / `impact not known`.
    static func impact(_ step: FixPlanDocument.Step) -> String {
        if let band = step.impactBand, band != "?" {
            return "measured \(band)" + (step.impactSeconds.map { ", about \(FormatText.seconds($0))" } ?? "")
        }
        if let band = step.estimatedBand { return "estimated \(band) (catalog)" }
        return "impact not known"
    }

    /// `kept (-2.10 s, -12.4 %; clean builds through hook)` or `unverified: xcblame verify ...`.
    static func verifyLine(_ step: FixPlanDocument.Step) -> String {
        let state = step.verify
        let label = FixVerifyWords.stateLabel(state)
        guard state.status != .unverified else {
            if step.mechanism == .hook || step.mechanism == .cli {
                return label + ": " + (step.commands.first { $0.hasPrefix("xcblame verify ") }
                    ?? "xcblame verify --rules \(step.ruleId) --kind \(step.verifyKind) --mechanism \(step.mechanism.rawValue)")
            }
            return label + (step.mechanism == .defaults ? " (verify does not measure defaults steps)" : " (nothing to measure: a manual step)")
        }
        var facts: [String] = []
        if let delta = state.deltaSeconds { facts.append(FormatText.deltaText(delta, state.deltaPct)) }
        var how = (state.kind ?? step.verifyKind) + " builds"
        if let mechanism = state.mechanism { how += " through " + mechanism.rawValue }
        facts.append(how)
        return label + " (" + facts.joined(separator: "; ") + ")"
    }

    static func hookLine(_ hook: FixPlanDocument.HookState) -> String {
        let file = hook.baseXCConfig.map { " (\($0))" } ?? ""
        let reason = hook.reason.map { ": " + $0 } ?? ""
        switch hook.status {
        case "installed": return "\(hook.configuration): installed\(file)"
        case "notInstalled": return "\(hook.configuration): not installed\(file): xcblame fix --install-hook appends one #include? line"
        case "generated": return "\(hook.configuration): generated project\(file)\(reason.isEmpty ? ": add the #include? line in the generator's source" : reason)"
        default: return "\(hook.configuration): \(hook.status)\(file)\(reason)"
        }
    }

    static func defaultsCommand(_ change: FixPlanDocument.DefaultsChange) -> String {
        guard let value = change.value else { return "defaults delete \(change.domain) \(change.key)" }
        return "defaults write \(change.domain) \(change.key)" + (change.type.map { " -\($0)" } ?? "") + " \(value)"
    }

    static func eventLine(_ event: FixPlanDocument.Event) -> String {
        let formatter = ISO8601DateFormatter()
        let what = (event.files + event.defaultsKeys).joined(separator: ", ")
        return formatter.string(from: event.at) + " " + event.action
            + (event.ruleIds.isEmpty ? "" : " " + event.ruleIds.joined(separator: ",")) + (what.isEmpty ? "" : ": " + what)
    }
}
