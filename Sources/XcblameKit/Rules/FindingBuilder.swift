import Foundation

/// Turns a predicate's `RuleHit` into a report `Finding`: shadowing (DESIGN §7.5), the generated-project downgrade
/// (RULES.md §10), fix kind, mechanism and commands (§7.3), band, confidence and severity (§7.1), signal key.
enum FindingBuilder {
    /// Levels above the overlay: the hook includes it from the project-level base xcconfig, so explicit values in
    /// the project file (project or target level), target xcconfigs and the command line all win over it.
    static let shadowingLevels: Set<Provenance.Level> = [.projectSettings, .targetXCConfig, .targetSettings, .commandLine]

    static func make(_ hit: RuleHit, spec: RuleSpec, scan: RuleScan) -> ReportDocument.Finding {
        var evidence = hit.evidence
        var overlayLines: [String] = []
        var commands: [String] = []
        let fixKind: String
        let mechanism: String
        let id = spec.id
        let generator = scan.project?.generator

        switch hit.apply {
        case .overlayDebug, .overlayRelease, .overlay:
            let shadowed = shadowedPairs(hit, scan: scan)
            let pairs = Set(hit.targets.flatMap { target in hit.configurations.map { "\(target)\u{1}\($0)" } })
            let covered = Set(shadowed.map { "\($0.target)\u{1}\($0.configuration)" })
            var groups: [(configuration: String, key: String, label: String, targets: [String])] = []
            for item in shadowed {
                if let index = groups.firstIndex(where: {
                    $0.configuration == item.configuration && $0.key == item.key && $0.label == item.label
                }) {
                    groups[index].targets.append(item.target)
                } else {
                    groups.append((item.configuration, item.key, item.label, [item.target]))
                }
            }
            evidence += groups.map {
                ReportDocument.EvidenceItem(kind: "setting", ref: $0.targets.joined(separator: "+") + ":\($0.configuration):\($0.key)",
                                            value: "shadowed, the overlay cannot win", provenance: $0.label)
            }
            let levels = scan.distinct(shadowed.map { $0.label })
            // A CocoaPods-generated xcconfig is regenerated by `pod install`: never edited (RULES.md §10, DESIGN §7.5).
            let pods = shadowed.filter { isPodsXCConfig($0.file) }
            if !pairs.isEmpty, pairs.isSubset(of: covered) {
                // v0.6 (docs/SCHEMA-v0.6.md Decision 2, probes Q1/Q3/Q9): shadowing is a hook-only concept. An -xcconfig
                // on the xcodebuild command line sits above every project level, so the overlay lines stay and the
                // fix planner delivers them through `cli` (hook: shadowed); Xcode builds get the recommendation.
                let recommendation = !pods.isEmpty
                    ? "recommend a Podfile post_install change (pod install regenerates the file)"
                    : generator.map { "recommend changing \(sourceFile($0))" } ?? "recommend removing the shadowing value"
                mechanism = (!pods.isEmpty ? "shadowed by a CocoaPods-generated xcconfig (\(levels.joined(separator: ", ")))"
                    : "shadowed by \(levels.joined(separator: ", "))")
                    + ": cli (an -xcconfig on the xcodebuild command line reaches every target; xcblame verify "
                    + "--mechanism cli measures it), or for Xcode builds \(recommendation)"
                fixKind = "overlay"
                overlayLines = hit.overlay.map { "\($0.key) = \($0.value) // xcblame \(id)" }
                commands = ["xcblame verify --rules \(id) --kind \(hit.verifyKind) --mechanism cli"]
                if let generator {
                    // The generator source is where the shadowing value lives: print the change there (RULES.md §10).
                    evidence += hit.overlay.map {
                        ReportDocument.EvidenceItem(kind: "file", ref: sourceFile(generator), value: describe(
                            .setting(key: $0.key, value: $0.value, configurations: hit.configurations), generator: generator))
                    }
                } else if !pods.isEmpty {
                    evidence += hit.overlay.map {
                        ReportDocument.EvidenceItem(kind: "file", ref: podfileRef(scan), value: postInstall(
                            key: $0.key, value: $0.value, configurations: hit.configurations))
                    }
                }
            } else {
                fixKind = "overlay"
                overlayLines = hit.overlay.map { "\($0.key) = \($0.value) // xcblame \(id)" }
                var text = "hook" + (generator.map { " (" + hookText($0, configuration: hit.configurations.first ?? "Debug") + ")" } ?? "")
                if !shadowed.isEmpty {
                    let targets = scan.distinct(shadowed.map(\.target))
                    text += "; shadowed for \(scan.targetsText(targets)) by \(levels.joined(separator: ", ")): "
                        + (pods.isEmpty ? "--edit-project" : "Podfile post_install")
                }
                mechanism = text
                commands = spec.verifyOnly
                    ? ["xcblame verify --rules \(id) --kind \(hit.verifyKind) --mechanism hook", "xcblame fix --rules \(id) --apply"]
                    : ["xcblame fix --rules \(id) --apply"]
            }
        case .cli:
            fixKind = "cli"
            mechanism = "cli"
            if !hit.cliArguments.isEmpty {
                commands = ["xcodebuild … " + hit.cliArguments.joined(separator: " ") + "  (CI invocation only)"]
            }
        case .defaults:
            fixKind = "defaults"
            mechanism = "defaults"
            commands = ["xcblame fix --rules \(id) --apply-defaults"]
        case .pbxproj where flagFile(hit, scan: scan) != nil:
            // The flag lives in an xcconfig: point at that file (a Pods one through the Podfile), never the pbxproj.
            let file = flagFile(hit, scan: scan)!
            fixKind = "recommend"
            if case let .removeFlag(key, flag) = hit.change {
                if isPodsXCConfig(file) {
                    mechanism = "recommend (CocoaPods-generated \(scan.displayPath(file)): Podfile post_install)"
                    evidence.append(ReportDocument.EvidenceItem(kind: "file", ref: podfileRef(scan),
                                                                value: postInstallRemove(key: key, flag: flag)))
                } else {
                    mechanism = "recommend (edit \(scan.displayPath(file)))"
                    evidence.append(ReportDocument.EvidenceItem(kind: "file", ref: scan.displayPath(file),
                                                                value: "remove \(flag) from \(key)"))
                }
            } else {
                mechanism = "recommend (edit \(scan.displayPath(file)))"
            }
        case .pbxproj, .scheme:
            if let generator {
                fixKind = "recommend"
                mechanism = "recommend (generated by \(displayName(generator)): change \(sourceFile(generator)))"
                if let change = hit.change {
                    evidence.append(ReportDocument.EvidenceItem(kind: "file", ref: sourceFile(generator),
                                                                value: describe(change, generator: generator)))
                }
            } else {
                fixKind = hit.apply == .scheme ? "scheme" : "project"
                mechanism = "--edit-project"
                commands = ["xcblame fix --rules \(id) --edit-project"]
            }
        case .manifest:
            fixKind = "manifest"
            mechanism = "--edit-project"
            commands = ["xcblame fix --rules \(id) --edit-project"]
        case .recommend:
            fixKind = "recommend"
            mechanism = "recommend"
            if let generator, let change = hit.change {
                evidence.append(ReportDocument.EvidenceItem(kind: "file", ref: sourceFile(generator),
                                                            value: describe(change, generator: generator)))
            }
        case .measure:
            fixKind = "measure"
            mechanism = "measure"
        }

        let band = hit.measured.map { Confidence.band(seconds: $0.seconds, share: $0.share) } ?? "?"
        if hit.measured == nil {
            evidence.append(ReportDocument.EvidenceItem(kind: "report", ref: "catalog", value: spec.impactContext))
        }
        let confidence = Confidence.level(tag: spec.evidenceTag, measured: hit.measured != nil && band != "?",
                                          lowered: scan.offlineSource)
        return ReportDocument.Finding(
            ruleId: id, title: hit.title,
            severity: Confidence.severity(spec, override: hit.severity, band: band).rawValue,
            impactBand: band, impactSeconds: hit.measured?.seconds.map(ReportDocument.round6),
            impactBasis: hit.measured?.basis, confidence: confidence, evidence: evidence.map(text),
            fixKind: fixKind, risk: spec.risk, mechanism: mechanism,
            signalKey: signalKey(spec.signalKeyTemplate, hit: hit), scopeTargets: hit.targets,
            scopeConfigurations: hit.configurations, evidenceDetails: evidence, fixCommands: commands,
            overlayLines: overlayLines, seeAlso: [], xcode: spec.xcode == "all" ? nil : spec.xcode,
            sources: spec.sources, needsMeasurement: Confidence.needsMeasurement(spec, band: band),
            inXcode: inXcode(hit, scan: scan),
            estimatedBand: band == "?" ? catalogBand(spec.impactContext) : nil)
    }

    /// The band a catalog impact line starts with (`M: Allegro …`, `XS on 14+`); nil for `?`, `Measured…`, `Diagnostic`.
    static func catalogBand(_ context: String) -> String? {
        let head = context.prefix { $0.isLetter }
        return ["XS", "S", "M", "L"].contains(String(head)) ? String(head) : nil
    }

    /// Where to make the change in Xcode (`Finding.inXcode`), with the labels of `XcodeSettingLabels`: one line per
    /// overlay assignment, flag removal, script phase or package pin; the `defaults write` line for an Xcode preference.
    static func inXcode(_ hit: RuleHit, scan: RuleScan) -> [String] {
        let targets = hit.targets.isEmpty ? "" : scan.targetsText(hit.targets)
        /// The value the project has now: the first setting evidence of `key` with a real value.
        func current(_ key: String) -> String? {
            hit.evidence.first { $0.kind == "setting" && $0.ref.hasSuffix(":" + key) && $0.value != nil
                && $0.value != "unset" && !($0.value ?? "").hasPrefix("shadowed") }?.value
        }
        // A generated project changes in its generator source (the evidence names it), never in Xcode's editor.
        if scan.project?.generator != nil {
            return hit.apply == .defaults ? hit.evidence.filter { $0.ref == "fix" }.compactMap(\.value).map { "Terminal: " + $0 } : []
        }
        var lines = hit.overlay.map {
            XcodeSettingLabels.changeLine(key: $0.key, from: current($0.key), to: $0.value, configurations: hit.configurations,
                                          targets: targets)
        }
        switch hit.change {
        case let .setting(key, value, configurations)? where !hit.overlay.contains(where: { $0.key == key }):
            lines.append(XcodeSettingLabels.changeLine(key: key, from: current(key), to: value,
                                                       configurations: configurations, targets: targets))
        case let .removeFlag(key, flag)? where hit.apply == .pbxproj && flagFile(hit, scan: scan) != nil:
            let file = flagFile(hit, scan: scan)!
            if !isPodsXCConfig(file) { lines.append("Edit \(scan.displayPath(file)): remove \(flag) from \(key)") }
        case let .removeFlag(key, flag)?:
            let scope = (targets.isEmpty ? "" : targets + ", ") + (hit.configurations.isEmpty ? "all configurations"
                : hit.configurations.joined(separator: " and "))
            lines.append("Build Settings › \(XcodeSettingLabels.row(key)) for \(scope): remove \(flag)")
        case let .scriptIO(phase, target)?:
            lines.append("Target \(target) › Build Phases › Run Script \"\(phase)\": list the files it reads under Input Files "
                + "and the files it writes under Output Files, and keep \"Based on dependency analysis\" checked")
        case let .scriptGuard(phase, target)?:
            lines.append("Target \(target) › Build Phases › Run Script \"\(phase)\": wrap the script in "
                + "if [ \"${CONFIGURATION}\" = \"Release\" ]; then … fi")
        case let .packagePin(url)?:
            let name = (url as NSString).lastPathComponent.replacingOccurrences(of: ".git", with: "")
            lines.append("Project › Package Dependencies › \(name): set Dependency Rule to Exact Version (or Up to Next Major "
                + "Version) instead of Branch")
        default: break
        }
        if hit.apply == .defaults, let command = hit.evidence.first(where: { $0.ref == "fix" })?.value {
            lines.append("Terminal: " + command)
        }
        // This Mac (ENV rules): where the setting lives in macOS or Xcode's settings.
        for item in hit.evidence {
            let value = item.value ?? ""
            if value.hasSuffix("share one DerivedData") {
                lines.append("Xcode › Settings › Locations › Derived Data: choose Custom and give each Xcode copy its own folder "
                    + "(or keep one Xcode installed)")
            } else if value == "not excluded from Time Machine" {
                lines.append("Terminal: tmutil addexclusion \(scan.displayPath(scan.probe.derivedDataPath()))")
            } else if value.hasPrefix("volume "), value.hasSuffix("% free") {
                lines.append("System Settings › General › Storage: free space on the disk that holds DerivedData "
                    + "(Xcode › Settings › Locations shows where it is)")
            }
        }
        return lines
    }

    /// (target, configuration, key) triples where a level above the overlay sets the key explicitly.
    static func shadowedPairs(_ hit: RuleHit, scan: RuleScan)
        -> [(target: String, configuration: String, key: String, label: String, file: String?)] {
        var out: [(target: String, configuration: String, key: String, label: String, file: String?)] = []
        for target in hit.targets {
            for configuration in hit.configurations {
                for (key, _) in hit.overlay {
                    if let provenance = scan.shadowing(target, key, configuration) {
                        out.append((target, configuration, key, scan.label(provenance) ?? provenance.level.rawValue,
                                    provenance.file))
                    }
                }
            }
        }
        return out
    }

    // MARK: - CocoaPods and xcconfig files

    /// A CocoaPods-generated xcconfig: under `Pods/Target Support Files/` or named `Pods-*.xcconfig`.
    static func isPodsXCConfig(_ path: String?) -> Bool {
        guard let path else { return false }
        let name = (path as NSString).lastPathComponent
        return path.contains("Pods/Target Support Files/") || (name.hasPrefix("Pods-") && name.hasSuffix(".xcconfig"))
    }

    /// The xcconfig that sets a flag-removal hit's key (first target and configuration with an xcconfig provenance),
    /// nil when the project file sets it (then `--edit-project` applies).
    static func flagFile(_ hit: RuleHit, scan: RuleScan) -> String? {
        guard case let .removeFlag(key, _) = hit.change else { return nil }
        for target in hit.targets {
            for configuration in hit.configurations {
                let provenance = scan.provenance(target, key, configuration)
                if provenance.level == .projectXCConfig || provenance.level == .targetXCConfig, let file = provenance.file {
                    return file
                }
            }
        }
        return nil
    }

    static func podfileRef(_ scan: RuleScan) -> String {
        scan.podfile.map { scan.displayPath($0.url.path) } ?? "Podfile"
    }

    /// One-line Podfile `post_install` that sets `key` in the generated aggregate xcconfigs (DESIGN §7.5).
    static func postInstall(key: String, value: String, configurations: [String]) -> String {
        let guardText = configurations.isEmpty ? "" : " if [" + configurations.map { "'\($0)'" }.joined(separator: ", ")
            + "].include?(name)"
        return "add to post_install: installer.aggregate_targets.each { |t| t.xcconfigs.each { |name, xc| "
            + "(xc.attributes['\(key)'] = '\(value)'; xc.save_as(t.xcconfig_path(name)))\(guardText) } }"
    }

    static func postInstallRemove(key: String, flag: String) -> String {
        "add to post_install: installer.aggregate_targets.each { |t| t.xcconfigs.each { |name, xc| "
            + "(xc.attributes['\(key)'] = xc.attributes['\(key)'].to_s.gsub('\(flag)', '').strip; "
            + "xc.save_as(t.xcconfig_path(name))) } }"
    }

    /// The one-line text form of an evidence item (`Acme:Debug:KEY = value (target settings (App.xcodeproj))`).
    static func text(_ item: ReportDocument.EvidenceItem) -> String {
        switch item.kind {
        case "setting":
            return "\(item.ref) = \(item.value ?? "unset")" + (item.provenance.map { " (\($0))" } ?? "")
        case "report" where item.ref == "catalog":
            return "catalog context, not measured here: " + (item.value ?? "")
        default:
            return item.value.map { "\(item.ref): \($0)" } ?? item.ref
        }
    }

    /// Fills `<name>` placeholders; `<targets>` / `<configs>` default to the scope (`*` when empty).
    static func signalKey(_ template: String, hit: RuleHit) -> String {
        var values = hit.keys
        if values["targets"] == nil { values["targets"] = hit.targets.isEmpty ? "*" : hit.targets.joined(separator: "+") }
        if values["configs"] == nil {
            values["configs"] = hit.configurations.isEmpty ? "*" : hit.configurations.joined(separator: "+")
        }
        var key = template
        for (name, value) in values { key = key.replacingOccurrences(of: "<\(name)>", with: value) }
        return key
    }

    // MARK: - Generated projects

    static func displayName(_ generator: ProjectModel.Generator) -> String {
        switch generator {
        case .xcodegen: return "XcodeGen"
        case .tuist: return "Tuist"
        case let .other(name): return name
        }
    }

    static func sourceFile(_ generator: ProjectModel.Generator) -> String {
        switch generator {
        case let .xcodegen(spec): return spec.lastPathComponent
        case let .tuist(manifest): return manifest.lastPathComponent
        case let .other(name): return "the \(name) source"
        }
    }

    /// Where the overlay hook goes in a generated project (DESIGN §7.5): printed, never applied.
    static func hookText(_ generator: ProjectModel.Generator, configuration: String) -> String {
        let hook = ".xcblame/hook-\(configuration).xcconfig"
        switch generator {
        case let .xcodegen(spec): return "XcodeGen: configFiles: {\(configuration): \(hook)} in \(spec.lastPathComponent)"
        case let .tuist(manifest):
            return "Tuist: .debug(name: \"\(configuration)\", xcconfig: \"\(hook)\") in \(manifest.lastPathComponent)"
        case let .other(name): return "\(name): include \(hook) from the generator's configuration"
        }
    }

    /// The generator-source change that replaces a pbxproj/scheme edit (RULES.md §10).
    static func describe(_ change: GeneratorChange, generator: ProjectModel.Generator) -> String {
        let file = sourceFile(generator)
        switch (change, generator) {
        case let (.setting(key, value, configurations), .xcodegen):
            return configurations.isEmpty ? "settings: base: {\(key): \(value)} in \(file)"
                : "settings: configs: {" + configurations.map { "\($0): {\(key): \(value)}" }.joined(separator: ", ")
                    + "} in \(file)"
        case let (.setting(key, value, configurations), .tuist):
            return configurations.isEmpty ? "settings: .settings(base: [\"\(key)\": \"\(value)\"]) in \(file)"
                : "settings: .settings(configurations: [" + configurations.map {
                    ".\($0.lowercased().hasPrefix("rel") ? "release" : "debug")(name: \"\($0)\", settings: [\"\(key)\": \"\(value)\"])"
                }.joined(separator: ", ") + "]) in \(file)"
        case let (.setting(key, value, _), _):
            return "set \(key) = \(value) in \(file)"
        case let (.removeFlag(key, flag), .xcodegen):
            return "remove \(flag) from \(key) under settings: in \(file)"
        case let (.removeFlag(key, flag), _):
            return "remove \(flag) from \"\(key)\" in the target settings in \(file)"
        case let (.scriptIO(phase, target), .xcodegen):
            return "target \(target): add inputFiles:/outputFiles: (or inputFileLists:/outputFileLists:) to the "
                + "preBuildScripts/postBuildScripts entry \"\(phase)\" in \(file)"
        case let (.scriptIO(phase, target), .tuist):
            return "target \(target): .pre/.post(script: …, name: \"\(phase)\", inputPaths: […], outputPaths: […]) in \(file)"
        case let (.scriptIO(phase, target), _):
            return "target \(target): declare inputs and outputs of \"\(phase)\" in \(file)"
        case let (.scriptGuard(phase, target), _):
            return "target \(target): wrap the script of \"\(phase)\" in if [ \"${CONFIGURATION}\" = \"Release\" ]; then … fi "
                + "in \(file)"
        case let (.packagePin(url), .xcodegen):
            return "packages: <name>: url: \(url), exactVersion: <the version in Package.resolved> in \(file)"
        case let (.packagePin(url), .tuist):
            return ".remote(url: \"\(url)\", requirement: .exact(\"<the version in Package.resolved>\")) in \(file)"
        case let (.packagePin(url), _):
            return "pin \(url) to a version in \(file)"
        }
    }
}
